# Deploy the AgentCore Gateway with config auto-synced from the
# CloudFormation stack outputs.
#
# Architecture:
#   Amazon Q Chat Agent → Cognito (client_credentials / 2LO)
#     → AgentCore Gateway (spice-optimiser-gateway)
#     → Lambda Function (tool dispatch + pipeline)
#
# It runs two steps:
#   1. sync_agentcore_config.py  — fills agentcore.json (Lambda target ARN, Cognito
#      authorizer), agentcore-policy.json (ARNs) and aws-targets.json (account,
#      region) from the live stack outputs.
#   2. agentcore deploy          — deploys the gateway configuration.
# Afterwards the two tracked files are restored to their committed placeholders.
#
# Prerequisites:
#   - AWS credentials configured (env vars, or pass --profile).
#   - Node.js 20+ on PATH and the AgentCore CLI 1.x:  npm install -g @aws/agentcore
#     (the project is a v0 AgentCore project; the 1.x CLI runs it in compatibility mode,
#     which reads cloud-assembly schema 54, hence aws-cdk-lib is pinned to 2.273.x)
#     (1.0 removed the -y flag; its --yes means "confirm deleting the stack when the
#     project declares nothing", which is never what this script wants, so it is not used)
#   - Python 3 with boto3 available.
#
# Usage:
#   scripts/deploy_mcp.sh [--stack-name NAME] [--region REGION] [--profile NAME]
#
# Deploy the CloudFormation stack FIRST; this only handles the gateway.

set -euo pipefail

STACK_NAME="spice-optimiser"
REGION="us-east-1"
PROFILE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stack-name) STACK_NAME="$2"; shift 2 ;;
    --region)     REGION="$2"; shift 2 ;;
    --profile)    PROFILE="$2"; shift 2 ;;
    -h|--help)
      grep '^#' "$0" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "$SCRIPT_DIR")"
PROJECT_DIR="$REPO_DIR/agentcore_project/spiceoptimisermcp"

SYNC_ARGS=(--stack-name "$STACK_NAME" --region "$REGION")
DEPLOY_ENV=(AWS_REGION="$REGION")
if [[ -n "$PROFILE" ]]; then
  SYNC_ARGS+=(--profile "$PROFILE")
  DEPLOY_ENV+=(AWS_PROFILE="$PROFILE")
fi

# The sync writes this account's real identifiers (Lambda ARN, Cognito pool and client,
# deployment account) into two tracked files. Those values are deploy-time inputs, not
# source: the committed files carry documentation placeholders, and a real account ID
# committed from here was a security-review finding. So the tracked files are copied
# aside first and put back when the deploy ends, however it ends. aws-targets.json is
# generated by the sync and is not tracked, so it is left with the real values the CLI
# needs for later `agentcore status` / `agentcore destroy` calls.
TRACKED_CONFIGS=("$PROJECT_DIR/agentcore/agentcore.json" "$REPO_DIR/agentcore-policy.json")
SAVED_DIR="$(mktemp -d)"
for f in "${TRACKED_CONFIGS[@]}"; do
  cp "$f" "$SAVED_DIR/$(basename "$f")"
done
restore_tracked_configs() {
  for f in "${TRACKED_CONFIGS[@]}"; do
    cp "$SAVED_DIR/$(basename "$f")" "$f"
  done
  rm -rf "$SAVED_DIR"
  echo "==> Restored agentcore.json and agentcore-policy.json to their committed form"
  echo "    (the deployed values live in the stack; re-run this script to deploy again)."
}
trap restore_tracked_configs EXIT

echo "==> Syncing AgentCore config from stack '$STACK_NAME' ($REGION)"
python3 "$SCRIPT_DIR/sync_agentcore_config.py" "${SYNC_ARGS[@]}"

echo "==> Installing the CDK app's pinned dependencies"
# The lockfile is the source of truth for the CDK app's dependency versions (they are
# reviewed and audited; see SECURITY.md). The AgentCore CLI would otherwise rewrite
# package.json to the versions it was tested with, which here means reintroducing the
# npm advisories the pinned aws-cdk-lib fixes, so its managed dependency sync is skipped
# and npm ci installs exactly what the lockfile says.
( cd "$PROJECT_DIR/agentcore/cdk" && npm ci --no-audit --no-fund --silent )

echo "==> Deploying AgentCore Gateway"
cd "$PROJECT_DIR"
env "${DEPLOY_ENV[@]}" AGENTCORE_SKIP_INSTALL=1 agentcore deploy --target default

echo "==> Done. AgentCore Gateway 'spice-optimiser-gateway' deployed."
echo "    Gateway invokes Lambda directly — no MCP server runtime needed."
